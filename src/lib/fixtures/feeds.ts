import type { Feed, FetchLogEntry, Folder } from "@/lib/types";

/*
 * Feeds and folders, ported from `hallmark/data.js`.
 *
 * Two fields moved on the way across, and the move is the point. The prototype
 * hung `folderId` and `subscribedAt` off the feed; ARCHITECTURE Appendix D puts
 * both on `subscriptions`, because a feed is SHARED and a following is PRIVATE.
 * Leaving them on the feed would have encoded one reader's filing into a row
 * ten readers share — the exact mistake the data model exists to prevent. They
 * live in `subscriptions.ts` instead.
 *
 * The sample's "now" is 2026-11-12T09:40:00Z. Every time is UTC and literal:
 * nothing here calls `Date.now()`, so a test that depends on these dates cannot
 * drift or flake.
 */

/**
 * 'MM-DDTHH:MM' -> ISO, UTC. The sample year is 2026.
 *
 * Emits the MILLISECOND form, `...:00.000Z`, so a fixture timestamp is
 * byte-identical to what `Date.prototype.toISOString()` returns for the same
 * instant. Without that, `service-parity.test.ts` compares `:00Z` against
 * `:00.000Z` with `toBe` and the seam test — M6's stated deliverable — can
 * never pass, over a difference no reader could see.
 */
export const D = (s: string) => new Date(`2026-${s}:00Z`).toISOString();

export const NOW = new Date("2026-11-12T09:40:00Z").toISOString();

/** One `fetch_log` row, with the zeroes spelled out so a partial is obvious. */
const L = (
  at: string,
  code: FetchLogEntry["code"],
  o: Partial<Omit<FetchLogEntry, "at" | "code">> = {},
): FetchLogEntry => ({
  at: D(at),
  code,
  itemsSeen: 0,
  itemsNew: 0,
  mergedByGuid: 0,
  mergedByUrl: 0,
  mergedByContent: 0,
  revised: 0,
  ...o,
});

