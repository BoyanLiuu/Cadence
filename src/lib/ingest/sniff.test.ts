import { readFileSync } from "node:fs";
import { join } from "node:path";

import { describe, expect, it } from "vitest";

import { parse } from "./parse";
import { sniff, sniffText } from "./sniff";

/*
 * What this suite is for: the most common user-reported failure in this whole
 * product — a publisher serving an HTML page where a feed used to be.
 *
 * The bug it prevents is subtle. If the format comes from `Content-Type`, an
 * HTML error page sent as `application/rss+xml` is handed to the XML parser,
 * yields zero items, and the feed reads as "nothing new this week" forever. The
 * reader cannot tell breakage from silence, and nobody notices for a month.
 */

const DIR = join(__dirname, "../../../test/fixtures/feeds");
const bytes = (f: string) => new Uint8Array(readFileSync(join(DIR, f)));

describe("sniffing reads bytes, never the Content-Type", () => {
  it("rejects an HTML page sent as application/rss+xml", () => {
    // The lie: the server claims a feed type. The bytes say otherwise, and the
    // bytes win — `parse` is not even given the header for format purposes.
    const result = parse(bytes("10-html-served-as-feed.html"), "application/rss+xml");
    expect(result.ok).toBe(false);
    expect(result.ok ? null : result.reason).toBe("not_a_feed");
  });

  it("rejects an HTML 404 body served with 200 OK", () => {
    const result = parse(bytes("11-html-404-with-200.html"), "application/rss+xml");
    expect(result.ok).toBe(false);
    expect(result.ok ? null : result.reason).toBe("not_a_feed");
  });

  it("accepts a real feed sent with a wrong, non-feed Content-Type", () => {
    // The mirror image, and the reason the header cannot be a gate either: a
    // feed served as text/plain is still a feed.
    const result = parse(bytes("01-rss2-cdata.xml"), "text/plain");
    expect(result.ok).toBe(true);
    expect(result.ok && result.dialect).toBe("rss2");
  });
});

describe("the root element decides the format", () => {
  it.each([
    ["01-rss2-cdata.xml", "rss2"],
    ["02-atom-xml-base.xml", "atom"],
    ["03-rdf-rss1.xml", "rss1"],
    ["04-json-feed.json", "json"],
  ])("%s sniffs as %s", (file, dialect) => {
    expect(sniff(bytes(file))).toBe(dialect);
  });

  it("matches on the local name, so any namespace prefix works", () => {
    // `<rdf:RDF>`, `<RDF>` and `<x:RDF>` are the same document. Hard-coding
    // the `rdf:` prefix is a real bug: the prefix is the author's choice.
    expect(sniffText('<rdf:RDF xmlns:rdf="..."><channel/></rdf:RDF>')).toBe("rss1");
    expect(sniffText('<RDF xmlns="..."><channel/></RDF>')).toBe("rss1");
    expect(sniffText('<x:RDF xmlns:x="..."><channel/></x:RDF>')).toBe("rss1");
  });

  it("looks past an XML declaration, comments and a doctype", () => {
    expect(
      sniffText(
        `<?xml version="1.0"?>\n<!-- generated by something -->\n<!DOCTYPE rss SYSTEM "x.dtd">\n<rss version="2.0"><channel/></rss>`,
      ),
    ).toBe("rss2");
  });

  it("calls well-formed XML that is not a feed unsupported, not not_a_feed", () => {
    // The distinction carries different copy: `not_a_feed` tells the reader
    // "this address serves a web page", which would be wrong for a sitemap.
    expect(sniffText(readFileSync(join(DIR, "30-xml-but-not-a-feed.xml"), "utf8"))).toBe("unknown");
  });

  it("needs an items array before calling a JSON body a feed", () => {
    expect(sniffText('{"version":"https://jsonfeed.org/version/1.1","items":[]}')).toBe("json");
    expect(sniffText('{"ok":true,"data":[1,2]}')).toBe("unknown");
    expect(sniffText("{not json at all")).toBe("unknown");
  });

  it("reports an empty body as unknown rather than guessing", () => {
    expect(sniffText("")).toBe("unknown");
    expect(sniffText("   \n\t ")).toBe("unknown");
  });

  it("detects HTML with no doctype, from the root element alone", () => {
    expect(sniffText("<html><body><h1>Moved</h1></body></html>")).toBe("not_a_feed");
  });
});
